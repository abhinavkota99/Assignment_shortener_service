package com.example.agentic.agents;

import com.example.agentic.engine.Json;
import com.example.agentic.workspace.FileOp;
import com.fasterxml.jackson.databind.JsonNode;
import java.util.ArrayList;
import java.util.List;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Documentation generated from the source of truth, so docs cannot drift from code:
 * {@code docs/API.md} from the route table in the API class plus the design's contract changes, and a
 * change record {@code docs/changes/<scenario>.md} tying requirements, decisions, tasks and risks together.
 */
public final class DocsAgent implements Agent {

    private static final Pattern ROUTE_TABLE = Pattern.compile("<pre>(.*?)</pre>", Pattern.DOTALL);
    /** Route table row: METHOD, path, purpose, responses; columns separated by two or more spaces. */
    private static final Pattern ROUTE_ROW = Pattern.compile("^(GET|POST|PUT|PATCH|DELETE|HEAD)\\s+(\\S+)\\s+(.+?)\\s{2,}(\\S.*)$");
    static final String API_SOURCE = "src/main/java/com/example/shortener/api/ShortenerApi.java";

    @Override
    public String name() {
        return "docs";
    }

    @Override
    public AgentResult execute(AgentContext ctx) throws AgentException {
        JsonNode req = ctx.input("requirements");
        JsonNode plan = ctx.input("plan");
        JsonNode design = ctx.input("design");

        StringBuilder api = new StringBuilder("# HTTP API\n\n_Generated by the docs agent from `ShortenerApi` - do not edit by hand._\n\n");
        if (ctx.workspace().exists(API_SOURCE)) {
            Matcher m = ROUTE_TABLE.matcher(ctx.workspace().read(API_SOURCE));
            if (m.find()) {
                api.append("| Method | Path | Purpose | Responses |\n|---|---|---|---|\n");
                for (String line : m.group(1).split("\n")) {
                    Matcher row = ROUTE_ROW.matcher(line.replaceFirst("^\\s*\\*\\s?", "").trim());
                    if (row.matches()) {
                        api.append("| ").append(row.group(1)).append(" | `").append(row.group(2)).append("` | ")
                                .append(row.group(3).trim()).append(" | ").append(row.group(4).trim()).append(" |\n");
                    }
                }
            }
        }
        api.append("\nErrors use `{\"error\":{\"code\":\"...\",\"message\":\"...\"}}`.\n");
        if (!design.path("apiChanges").isEmpty()) {
            api.append("\n## Changes in this release\n\n");
            design.path("apiChanges").forEach(c -> api.append("- ").append(c.asText()).append('\n'));
        }

        StringBuilder change = new StringBuilder("# Change record: ").append(ctx.scenario().title()).append("\n\n")
                .append("_Run `").append(ctx.runId()).append("`. Generated by the docs agent._\n\n")
                .append("## Requirement (as stated)\n\n> ").append(ctx.scenario().requirement()).append("\n\n")
                .append("## Interpreted as\n\n");
        req.path("capabilities").forEach(c -> {
            change.append("- **").append(c.path("title").asText()).append("** (").append(c.path("source").asText()).append(")\n");
            c.path("requirements").forEach(r -> change.append("  - ").append(r.path("id").asText()).append(": ")
                    .append(r.path("text").asText()).append('\n'));
        });
        section(change, "Assumptions", req.path("assumptions"));
        section(change, "Out of scope", req.path("outOfScope"));
        change.append("\n## Plan\n\n");
        plan.path("tasks").forEach(t -> change.append("- `").append(t.path("id").asText()).append("` ").append(t.path("title").asText())
                .append(t.path("dependsOn").isEmpty() ? "" : " (after " + t.path("dependsOn") + ")").append('\n'));
        plan.path("alreadySatisfied").forEach(s -> change.append("- reused existing: ").append(s.path("capability").asText()).append('\n'));
        plan.path("excluded").forEach(x -> change.append("- excluded: ").append(x.path("capability").asText()).append(" - ")
                .append(x.path("reason").asText()).append('\n'));
        section(change, "API changes", design.path("apiChanges"));
        section(change, "Data changes", design.path("dataChanges"));
        section(change, "Risks", design.path("risks"));

        String changePath = "docs/changes/" + ctx.scenario().id() + ".md";
        List<FileOp> ops = new ArrayList<>();
        for (String[] f : new String[][] {{"docs/API.md", api.toString()}, {changePath, change.toString()}}) {
            if (ctx.workspace().exists(f[0])) {
                ops.add(new FileOp("delete", f[0], null, null, null));
            }
            ops.add(FileOp.create(f[0], f[1]));
        }
        List<String> changed = ctx.workspace().apply(ctx.stage().id(), ops);
        return new AgentResult("generated " + changed.size() + " documents")
                .artifact("docs", Json.object().set("files", Json.tree(List.of("docs/API.md", changePath))))
                .changed(changed);
    }

    private static void section(StringBuilder sb, String title, JsonNode items) {
        if (items.isEmpty()) {
            return;
        }
        sb.append("\n## ").append(title).append("\n\n");
        items.forEach(i -> sb.append("- ").append(i.asText()).append('\n'));
    }
}
